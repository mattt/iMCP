"""Generate both README hero images from the SVG assets."""

import math
from copy import deepcopy
from pathlib import Path
from xml.etree import ElementTree as ET

ASSETS = Path(__file__).resolve().parents[1] / "Assets"
SVG = "http://www.w3.org/2000/svg"
ET.register_namespace("", SVG)

# Arrange icons by hue, from red through green and blue to purple.
# Each entry pairs an asset name with its dark appearance background color.
SERVICES = (
    ("calendar", "#ff453a"),
    ("voice-memos", "#ff453a"),
    ("contacts", "#ac8e68"),
    ("reminders", "#ff9f0a"),
    ("home", "#ff9f0a"),
    ("notes", "#ffd60a"),
    ("messages", "#28d74b"),
    ("phone", "#28d74b"),
    ("voicemail", "#28d74b"),
    ("weather", "#5ac8f5"),
    ("location", "#0a84ff"),
    ("mail", "#0a84ff"),
    ("shortcuts", "#5e5ce6"),
    ("maps", "#bf5af2"),
    ("music", "#000"),
)

WIDTH = 1012
MARGIN = 40
ICON_SIZE = 86
# Space neighboring icons this far apart, center to center,
# in a row and between the rows.
PITCH = ICON_SIZE + 12
OUTER_RADIUS = 380
INNER_RADIUS = OUTER_RADIUS - PITCH
ARC_TOP = MARGIN + ICON_SIZE / 2
# Leave this much space between the lowest icons and the wordmark.
WORDMARK_GAP = 48
# The lettering spans these y-coordinates in wordmark.svg.
WORDMARK_TOP, WORDMARK_BOTTOM = 310, 511


def arc_angles(count: int, radius: float) -> list[float]:
    """Return angles that space icons one pitch apart along an arc."""
    step = 2 * math.asin(PITCH / 2 / radius)
    return [(index - (count - 1) / 2) * step for index in range(count)]


def icon_centers(count: int) -> list[tuple[float, float]]:
    """Stack centers in two concentric rows, from left to right.

    The outer row is longer, so it holds more icons.
    Choose the split that extends the outer row
    about half a step past each end of the inner row.
    """
    outer_step = 2 * math.asin(PITCH / 2 / OUTER_RADIUS)

    def overhang_error(outer_count: int) -> float:
        outer = arc_angles(outer_count, OUTER_RADIUS)
        inner = arc_angles(count - outer_count, INNER_RADIUS) or [0]
        return abs(outer[-1] - inner[-1] - outer_step / 2)

    outer_count = min(range((count + 1) // 2, count + 1), key=overhang_error)
    placements = [(angle, OUTER_RADIUS) for angle in arc_angles(outer_count, OUTER_RADIUS)]
    placements += [
        (angle, INNER_RADIUS) for angle in arc_angles(count - outer_count, INNER_RADIUS)
    ]
    return [
        (
            WIDTH / 2 + radius * math.sin(angle),
            ARC_TOP + OUTER_RADIUS - radius * math.cos(angle),
        )
        for angle, radius in sorted(placements)
    ]


def generate(theme: str) -> None:
    centers = icon_centers(len(SERVICES))
    icons_bottom = max(y for _, y in centers) + ICON_SIZE / 2
    wordmark_offset = icons_bottom + WORDMARK_GAP - WORDMARK_TOP
    height = WORDMARK_BOTTOM + wordmark_offset + MARGIN

    root = ET.Element(f"{{{SVG}}}svg", {"viewBox": f"0 0 {WIDTH} {height:.0f}"})
    root.append(ET.Comment(" Generated by Scripts/generate-hero.py. Do not edit. "))
    ET.SubElement(root, f"{{{SVG}}}title").text = "iMCP"

    wordmark = ET.parse(ASSETS / "wordmark.svg").getroot()
    lettering = deepcopy(wordmark.find(f"{{{SVG}}}g"))
    lettering.set("fill", "#fff" if theme == "dark" else "#000")
    lettering.set("transform", f"translate(0 {wordmark_offset:.3f})")
    root.append(lettering)

    for (name, dark_color), (x, y) in zip(SERVICES, centers):
        icon = ET.parse(ASSETS / f"{name}.svg").getroot()
        icon.set("x", f"{x - ICON_SIZE / 2:.3f}")
        icon.set("y", f"{y - ICON_SIZE / 2:.3f}")
        icon.set("width", str(ICON_SIZE))
        icon.set("height", str(ICON_SIZE))
        ET.SubElement(icon, f"{{{SVG}}}title").text = name.replace("-", " ").title()
        if theme == "dark":
            icon.find(f"{{{SVG}}}circle").set("fill", dark_color)
        root.append(icon)

    ET.indent(root, space="  ")
    output = ET.tostring(root, encoding="unicode")
    (ASSETS / f"hero-{theme}.svg").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n' + output + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    for theme in ("light", "dark"):
        generate(theme)
